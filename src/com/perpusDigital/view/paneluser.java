    private void jTableUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableUserMouseClicked
        int baris = jTableUser.getSelectedRow();
    if (baris != -1) {
        // Mengambil data dari tabel dan memasukkannya kembali ke form input
        txt_username.setText(jTableUser.getValueAt(baris, 1).toString());
        txt_password.setText(""); // Password dikosongkan demi keamanan saat edit
        txt_email.setText(jTableUser.getValueAt(baris, 2).toString());
        cb_role.setSelectedItem(jTableUser.getValueAt(baris, 3).toString());
        
        txt_username.setEnabled(false); // Username dikunci agar tidak bisa diubah saat mengedit
    }
    }//GEN-LAST:event_jTableUserMouseClicked


