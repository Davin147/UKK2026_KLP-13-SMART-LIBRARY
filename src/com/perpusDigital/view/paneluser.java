    private void btn_ubahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_ubahActionPerformed
       String username = txt_username.getText().trim();
    String password = new String(txt_password.getText()).trim();
    String email = txt_email.getText().trim(); // <-- AMBIL EMAIL
    String role = cb_role.getSelectedItem().toString();

    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih data pada tabel atau isi form terlebih dahulu!");
        return;
    }

    try {
        Connection conn = Koneksi.getKoneksi();
        // Perbarui query SQL untuk menyertakan email
        String sql = "UPDATE petugas SET password = ?, email = ?, role = ? WHERE username = ?";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, password); 
        pst.setString(2, email);   
        pst.setString(3, role);     
        pst.setString(4, username); 
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data akun berhasil diperbarui!");
        loadData();
        resetForm();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal memperbarui data: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_ubahActionPerformed

    private void btn_simpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_simpanActionPerformed
        String username = txt_username.getText().trim();
    String password = new String(txt_password.getText()).trim();
    String email = txt_email.getText().trim(); // <-- TAMBAHKAN INI AGAR EMAIL TERBACA
    String role = cb_role.getSelectedItem().toString();

    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Username dan Password tidak boleh kosong!");
        return;
    }

    try {
        Connection conn = Koneksi.getKoneksi();
        String sql = "INSERT INTO petugas (username, password, email, role) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, username);
        pst.setString(2, password);
        pst.setString(3, email);   
        pst.setString(4, role);     
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Akun berhasil ditambahkan!");
        loadData();
        resetForm();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal menyimpan akun (Kemungkinan username sudah ada): " + e.getMessage());
    }
    }//GEN-LAST:event_btn_simpanActionPerformed

    private void btn_hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_hapusActionPerformed
        String username = txt_username.getText().trim();

        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih akun yang ingin dihapus dari tabel!");
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menghapus akun " + username + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                Connection conn = Koneksi.getKoneksi();
                String sql = "DELETE FROM petugas WHERE username = ?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, username);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(this, "Akun berhasil dihapus!");
                loadData();
                resetForm();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus akun: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btn_hapusActionPerformed

