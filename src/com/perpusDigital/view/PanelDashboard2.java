    // Method untuk memuat statistik angka di kartu ringkasan
   public void loadDashboardData() {
        try {
            Connection conn = com.perpusDigital.config.Koneksi.getKoneksi();
            Statement stm = conn.createStatement();

            // 1. Hitung Total Buku
            ResultSet rsBuku = stm.executeQuery("SELECT COUNT(*) AS total FROM buku");
            if (rsBuku.next()) {
                lblTotalBuku.setText(rsBuku.getString("total"));
            }

            // 2. Hitung Total Anggota
            ResultSet rsAnggota = stm.executeQuery("SELECT COUNT(*) AS total FROM anggota");
            if (rsAnggota.next()) {
                lblTotalAnggota.setText(rsAnggota.getString("total"));
            }

            // 3. Hitung Buku yang Masih Dipinjam
            ResultSet rsPinjam = stm.executeQuery("SELECT COUNT(*) AS total FROM peminjaman WHERE status = 'Dipinjam'");
        if (rsPinjam.next()) {
        lblTotalDipinjam.setText(rsPinjam.getString("total"));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat statistik dashboard: " + e.getMessage());
        }
    }

    // Method untuk memuat tabel aktivitas peminjaman terbaru (Opsional jika sudah ada JTable)
    public void loadRecentActivity() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nama Anggota");
        model.addColumn("Judul Buku");
        model.addColumn("Tanggal Pinjam");
        model.addColumn("Status");

        try {
            String sql = "SELECT p.id_peminjaman, a.nama, b.judul, p.tanggal_pinjam, p.status " +
                         "FROM peminjaman p " +
                         "JOIN anggota a ON p.id_anggota = a.id_anggota " +
                         "JOIN buku b ON p.id_buku = b.id_buku " +
                         "ORDER BY p.id_peminjaman DESC LIMIT 5";
                         
            Connection conn = com.perpusDigital.config.Koneksi.getKoneksi();
            Statement stm = conn.createStatement();
            ResultSet res = stm.executeQuery(sql);

            while (res.next()) {
                model.addRow(new Object[]{
                    res.getInt("id_peminjaman"),
                    res.getString("nama"),
                    res.getString("judul"),
                    res.getString("tanggal_pinjam"),
                    res.getString("status")
                });
            }
            // Jika Anda menambahkan JTable di bawah kartu, beri nama variabelnya tableAktivitas
            // tableAktivitas.setModel(model);
        } catch (Exception e) {
            // Abaikan jika JTable belum dipasang
        }
    }
    

