    public void loadDataAnggota() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("No");
    model.addColumn("Nama");
    model.addColumn("NIS");
    model.addColumn("Kelas");
    model.addColumn("Jenis Kelamin");
    model.addColumn("Telepon");
    model.addColumn("Kouta Peminjaman");

    try {
        int no = 1;
        String sql = "SELECT * FROM anggota";
        Connection conn = com.perpusDigital.config.Koneksi.getKoneksi();
        Statement stm = conn.createStatement();
        ResultSet res = stm.executeQuery(sql);

        while (res.next()) {
            model.addRow(new Object[]{
                no++,
                res.getString("nama_anggota"),
                res.getString("nis"),
                res.getString("kelas"),
                res.getString("jenis_kelamin"),
                res.getString("no_hp"),
                res.getString("kouta_peminjaman")
            });
        }
        tableAnggota.setModel(model); // tableAnggota adalah JTable Anda
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal memuat data anggota: " + e.getMessage());
    }
}
    
