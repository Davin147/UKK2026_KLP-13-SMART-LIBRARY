    private void btn_tambah1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_tambah1ActionPerformed
        // Meminta inputan via Pop-up Dialog
        String judul = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Judul Buku:");
        if (judul == null || judul.trim().isEmpty()) return; // Batal jika kosong

        String penulis = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Penulis:");
        String penerbit = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Penerbit:");
        String kategori = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Kategori:");
        String tahunStr = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Tahun Terbit:");
        String stokStr = javax.swing.JOptionPane.showInputDialog(this, "Masukkan Jumlah Stok:");

        try {
            int tahun = Integer.parseInt(tahunStr);
            int stok = Integer.parseInt(stokStr);

            String sql = "INSERT INTO buku (judul_buku, penulis, penerbit, kategori, tahun_terbit, stok) VALUES (?, ?, ?, ?, ?, ?)";
            java.sql.Connection conn =
            Koneksi.getKoneksi();
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, judul);
            pst.setString(2, penulis);
            pst.setString(3, penerbit);
            pst.setString(4, kategori);
            pst.setInt(5, tahun);
            pst.setInt(6, stok);

            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Data Buku Berhasil Disimpan!");
            loadDataBuku(); // Refresh isi tabel
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Tahun dan Stok harus berupa angka!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Simpan: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_tambah1ActionPerformed

    private void btn_hapus1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_hapus1ActionPerformed
        int row = tabel_buku.getSelectedRow();
        if (row != -1) {
            String judul = tabel_buku.getValueAt(row, 1).toString();
            int confirm = JOptionPane.showConfirmDialog(this, "Hapus buku " + judul + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION);

            if (confirm == JOptionPane.YES_OPTION) {
                try {
                    String sql = "DELETE FROM buku WHERE judul = ?";
                    Connection conn = com.perpusDigital.config.Koneksi.getKoneksi();
                    PreparedStatement pst = conn.prepareStatement(sql);
                    pst.setString(1, judul);
                    pst.executeUpdate();

                    JOptionPane.showMessageDialog(this, "Data Berhasil Dihapus!");
                    loadDataBuku();
                } catch (HeadlessException | SQLException e) {
                    JOptionPane.showMessageDialog(this, "Gagal Hapus: " + e.getMessage());
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Pilih data pada tabel terlebih dahulu!");
        }
    }//GEN-LAST:event_btn_hapus1ActionPerformed

