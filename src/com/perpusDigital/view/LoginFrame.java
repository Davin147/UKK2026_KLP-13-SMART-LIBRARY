    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txt_username.getText().trim();
        String password = new String(txt_password.getPassword()).trim();

        // 2. Validasi jika kosong
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username dan Password tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // 3. Ambil koneksi database
            Connection conn = Koneksi.getKoneksi();
            
            // 4. Query langsung ke tabel 'petugas'
            String sql = "SELECT * FROM petugas WHERE username = ? AND password = ?";
            PreparedStatement pst = conn.prepareStatement(sql);
            
            pst.setString(1, username);
            pst.setString(2, password);
            
            ResultSet res = pst.executeQuery();

            // 5. Cek hasil query
            if (res.next()) {
                // Ambil nilai role dan bersihkan spasi tersembunyi
                String role = res.getString("role").trim(); 
                
                if (role.equalsIgnoreCase("admin")) {
                    JOptionPane.showMessageDialog(this, "Login Berhasil sebagai Admin!");
                    new formAdmin().setVisible(true); // Membuka form admin
                    this.dispose(); // Menutup form login
                    
                } else if (role.equalsIgnoreCase("petugas")) {
                    JOptionPane.showMessageDialog(this, "Login Berhasil sebagai Petugas!");
                    new MainFrame().setVisible(true); // Membuka MainFrame petugas
                    this.dispose(); // Menutup form login
                } else {
                    JOptionPane.showMessageDialog(this, "Role tidak dikenali: " + role, "Peringatan", JOptionPane.WARNING_MESSAGE);
                }
                
            } else {
                // Jika username atau password tidak cocok
                JOptionPane.showMessageDialog(this, "Username atau Password salah!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                txt_password.setText("");
                txt_username.requestFocus();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan koneksi: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

